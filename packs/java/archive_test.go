// zipOf builds an archive from name -> content.
func zipOf(t *testing.T, files map[string][]byte) []byte {
	t.Helper()
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	for name, data := range files {
		w, err := zw.Create(name)
		if err != nil {
			t.Fatal(err)
		}
		w.Write(data)
	}
	if err := zw.Close(); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

func props(g, a, v string) []byte {
	return []byte("#Generated by Maven\ngroupId=" + g + "\nartifactId=" + a + "\nversion=" + v + "\n")
}

func TestSpringBootJar(t *testing.T) {
	jackson := zipOf(t, map[string][]byte{"META-INF/maven/com.fasterxml.jackson.core/jackson-core/pom.properties": props("com.fasterxml.jackson.core", "jackson-core", "2.15.2")})
	log4j := zipOf(t, map[string][]byte{"META-INF/maven/org.apache.logging.log4j/log4j-core/pom.properties": props("org.apache.logging.log4j", "log4j-core", "2.14.1")})
	noMeta := zipOf(t, map[string][]byte{"com/example/Thing.class": []byte("x")})
	app := zipOf(t, map[string][]byte{
		"META-INF/maven/com.acme/shop/pom.properties": props("com.acme", "shop", "3.0.0"),
		"BOOT-INF/lib/jackson-core-2.15.2.jar":        jackson,
		"BOOT-INF/lib/log4j-core-2.14.1.jar":          log4j,
		"BOOT-INF/lib/legacy.jar":                     noMeta,
	})
	out, _ := Scan(&pack.Request{Files: []pack.File{{Path: "opt/shop/shop.jar", Content: app}}})
	if find(out, "pkg:maven/com.acme/shop@3.0.0") != nil {
		t.Error("the application's own module was reported as a dependency")
	}
	o := find(out, "pkg:maven/org.apache.logging.log4j/log4j-core@2.14.1")
	if o == nil || o.Location != "opt/shop/shop.jar" || o.Evidence["archive_path"] != "BOOT-INF/lib/log4j-core-2.14.1.jar" {
		t.Fatalf("log4j: %+v", o)
	}
	if find(out, "pkg:maven/com.fasterxml.jackson.core/jackson-core@2.15.2") == nil {
		t.Error("jackson missing")
	}
	if c := coverage(out, "maven:opt/shop/shop.jar"); c.Status != "partial" || !strings.Contains(c.Reason, "1 bundled") {
		t.Errorf("coverage: %+v", c)
	}
}

func TestPlainJarAndNestedEar(t *testing.T) {
	lib := zipOf(t, map[string][]byte{"META-INF/maven/commons-io/commons-io/pom.properties": props("commons-io", "commons-io", "2.11.0")})
	out, _ := Scan(&pack.Request{Files: []pack.File{{Path: "lib/commons-io-2.11.0.jar", Content: lib}}})
	if find(out, "pkg:maven/commons-io/commons-io@2.11.0") == nil || coverage(out, "maven:lib/commons-io-2.11.0.jar").Status != "checked" {
		t.Errorf("plain library jar: %+v %+v", out.Observations, out.Coverage)
	}

	inner := zipOf(t, map[string][]byte{"META-INF/maven/org.yaml/snakeyaml/pom.properties": props("org.yaml", "snakeyaml", "1.33")})
	war := zipOf(t, map[string][]byte{"WEB-INF/lib/snakeyaml-1.33.jar": inner, "META-INF/maven/com.acme/web/pom.properties": props("com.acme", "web", "1.0")})
	ear := zipOf(t, map[string][]byte{"web.war": war})
	out, _ = Scan(&pack.Request{Files: []pack.File{{Path: "deploy/app.ear", Content: ear}}})
	if find(out, "pkg:maven/com.acme/web@1.0") != nil {
		t.Error("the WAR's own module was reported as a dependency")
	}
	o := find(out, "pkg:maven/org.yaml/snakeyaml@1.33")
	if o == nil || o.Evidence["archive_path"] != "web.war/WEB-INF/lib/snakeyaml-1.33.jar" {
		t.Errorf("ear > war > jar: %+v", out.Observations)
	}

	out, _ = Scan(&pack.Request{Files: []pack.File{{Path: "broken.jar", Content: []byte("not a zip")}}})
	if c := coverage(out, "maven:broken.jar"); c.Status != "failed" {
		t.Errorf("broken jar: %+v", c)
	}
}
