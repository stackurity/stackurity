// phpVersionH is main/php_version.h as PHP 8.3.14's make install writes it.
const phpVersionH = `/* automatically generated by configure */
/* edit configure.ac to change version number */
#define PHP_MAJOR_VERSION 8
#define PHP_MINOR_VERSION 3
#define PHP_RELEASE_VERSION 14
#define PHP_EXTRA_VERSION ""
#define PHP_VERSION "8.3.14"
#define PHP_VERSION_ID 80314
`

// nodeVersionH is the part of node_version.h that matters, as in 22.11.0.
const nodeVersionH = `#ifndef SRC_NODE_VERSION_H_
#define SRC_NODE_VERSION_H_

#define NODE_MAJOR_VERSION 22
#define NODE_MINOR_VERSION 11
#define NODE_PATCH_VERSION 0

#define NODE_VERSION_IS_LTS 1
#define NODE_VERSION_LTS_CODENAME "Jod"
`

// officialRuntimeRoot is laid out like the official php:8.3-cli or
// node:22-slim image: Debian's package database for the base system, and
// the runtime built from source into /usr/local, which no package owns.
func officialRuntimeRoot(t *testing.T, bin, header, headerData string) *pyRoot {
	r := newPyRoot(t)
	r.file("usr/lib/os-release", "ID=debian\nVERSION_ID=12\nVERSION_CODENAME=bookworm\nPRETTY_NAME=\"Debian GNU/Linux 12 (bookworm)\"\n", 0o644)
	r.link("etc/os-release", "../usr/lib/os-release")
	r.file("var/lib/dpkg/status", "Package: libc6\nStatus: install ok installed\nArchitecture: amd64\nVersion: 2.36-9+deb12u8\n\n", 0o644)
	r.file("var/lib/dpkg/info/libc6:amd64.list", "/.\n/usr/bin/ldd\n/usr/lib/x86_64-linux-gnu/libc.so.6\n", 0o644)
	r.file(bin, "\x7fELF", 0o755)
	if header != "" {
		r.file(header, headerData, 0o644)
	}
	return r
}

func onlyRuntime(t *testing.T, got map[string]model.Observation, product string) model.Observation {
	t.Helper()
	var found []model.Observation
	for _, o := range got {
		if o.Purl == "pkg:generic/"+product || strings.HasPrefix(o.Purl, "pkg:generic/"+product+"@") {
			found = append(found, o)
		}
	}
	if len(found) != 1 {
		t.Fatalf("want one %s, got %v", product, keys(got))
	}
	return found[0]
}

// The official php image's PHP is read from php_version.h: the exact
// release, confirmed, without running anything.
func TestImagePHPFromHeader(t *testing.T) {
	r := officialRuntimeRoot(t, "usr/local/bin/php", "usr/local/include/php/main/php_version.h", phpVersionH)
	got, _ := runtimes(t, imageCollector(r.root, map[string]string{"PHP_VERSION": "8.3.14"}))
	o := onlyRuntime(t, got, "php")
	if o.Purl != "pkg:generic/php@8.3.14" || o.Confidence != model.ConfidenceConfirmed ||
		o.Evidence["detected_by"] != "header" || o.Evidence["version_file"] != "/usr/local/include/php/main/php_version.h" {
		t.Errorf("php = %+v", o)
	}
	if o.Evidence["not_run"] == "" {
		t.Errorf("evidence should still say the binary was not run: %v", o.Evidence)
	}
}

// Without the headers, the image's PHP_VERSION gives the release.
func TestImagePHPFromEnv(t *testing.T) {
	r := officialRuntimeRoot(t, "usr/local/bin/php", "", "")
	got, _ := runtimes(t, imageCollector(r.root, map[string]string{"PHP_VERSION": "8.3.14"}))
	o := onlyRuntime(t, got, "php")
	if o.Purl != "pkg:generic/php@8.3.14" || o.Confidence != model.ConfidenceInferred ||
		o.Evidence["detected_by"] != "image-env" || o.Evidence["version_env"] != "PHP_VERSION=8.3.14" {
		t.Errorf("php = %+v", o)
	}
}

// With neither, PHP stays versionless, as before: nothing is invented.
func TestImagePHPNoVersionSource(t *testing.T) {
	r := officialRuntimeRoot(t, "usr/local/bin/php", "", "")
	for _, env := range []map[string]string{nil, {"PHP_VERSION": "not-a-version"}} {
		got, _ := runtimes(t, imageCollector(r.root, env))
		o := onlyRuntime(t, got, "php")
		if o.Purl != "pkg:generic/php" || o.Version != "" || o.Confidence != model.ConfidenceUnknown {
			t.Errorf("env %v: php = %+v", env, o)
		}
	}
}

// PHP_VERSION is not applied to a PHP outside /usr/local/bin.
func TestImagePHPEnvOnlyForUsrLocal(t *testing.T) {
	r := officialRuntimeRoot(t, "opt/php/bin/php", "", "")
	got, _ := runtimes(t, imageCollector(r.root, map[string]string{"PHP_VERSION": "8.3.14"}))
	o := onlyRuntime(t, got, "php")
	if o.Version != "" {
		t.Errorf("PHP_VERSION applied to /opt/php/bin/php: %+v", o)
	}

	// Its own headers are still read.
	r.file("opt/php/include/php/main/php_version.h", phpVersionH, 0o644)
	got, _ = runtimes(t, imageCollector(r.root, map[string]string{"PHP_VERSION": "8.1.0"}))
	o = onlyRuntime(t, got, "php")
	if o.Purl != "pkg:generic/php@8.3.14" || o.Evidence["detected_by"] != "header" {
		t.Errorf("php = %+v", o)
	}
}

