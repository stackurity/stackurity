// zipOf builds an archive with the given entries, in name order.
func zipOf(t *testing.T, files map[string][]byte) []byte {
	t.Helper()
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	slices.Sort(names)
	for _, n := range names {
		w, err := zw.Create(n)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := w.Write(files[n]); err != nil {
			t.Fatal(err)
		}
	}
	if err := zw.Close(); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

// rollerProps is roller-version.properties as a Roller release build
// writes it (6.1.4's WEB-INF/classes copy).
func rollerProps(v string) []byte {
	return []byte("ro.version=" + v + "\nro.revision=rfaafe379e353dc6a44d350734e4d8113d666a3be\nro.buildTime=1728247943514\nro.buildUser=dave\n")
}

func pomProps(g, a, v string) []byte {
	return []byte("#Generated by Maven\nversion=" + v + "\ngroupId=" + g + "\nartifactId=" + a + "\n")
}

// mavenJar is a library JAR with its Maven metadata.
func mavenJar(t *testing.T, g, a, v string) []byte {
	return zipOf(t, map[string][]byte{"META-INF/maven/" + g + "/" + a + "/pom.properties": pomProps(g, a, v), "org/x/X.class": []byte("cafe")})
}

// javaPack stands in for the Java stack pack: the pom.properties of each
// JAR it is given, and of the JARs in a WAR's WEB-INF/lib.
type javaPack struct{ files *[]string }

func (javaPack) ID() string { return "java" }
func (javaPack) Matches(name string) bool {
	return strings.HasSuffix(name, ".jar") || strings.HasSuffix(name, ".war")
}
func (j javaPack) Scan(_ context.Context, files []pack.File) ([]model.Observation, []model.CoverageItem, error) {
	var obs []model.Observation
	var cov []model.CoverageItem
	var read func(p string, data []byte, depth int)
	read = func(p string, data []byte, depth int) {
		zr, err := zip.NewReader(bytes.NewReader(data), int64(len(data)))
		if err != nil || depth > 1 {
			return
		}
		for _, e := range zr.File {
			switch {
			case strings.HasSuffix(e.Name, "/pom.properties"):
				b, _ := readZipEntry(e, 1<<10)
				props := map[string]string{}
				for _, l := range strings.Split(string(b), "\n") {
					if k, v, ok := strings.Cut(l, "="); ok {
						props[k] = v
					}
				}
				obs = append(obs, model.Observation{Purl: fmt.Sprintf("pkg:maven/%s/%s@%s", props["groupId"], props["artifactId"], props["version"]),
					Version: props["version"], Location: p, Confidence: model.ConfidenceConfirmed})
			case strings.HasSuffix(e.Name, ".jar"):
				b, _ := readZipEntry(e, 1<<20)
				read(p, b, depth+1)
			}
		}
	}
	for _, f := range files {
		if j.files != nil {
			*j.files = append(*j.files, f.Path)
		}
		read(f.Path, f.Content, 0)
		cov = append(cov, model.CoverageItem{Scope: "pack:java:" + f.Path, Status: "checked"})
	}
	return obs, cov, nil
}

func findPurl(a App, prefix string) *model.Observation {
	for i := range a.Observations {
		if strings.HasPrefix(a.Observations[i].Purl, prefix) {
			return &a.Observations[i]
		}
	}
	return nil
}

func findScope(a App, prefix string) *model.CoverageItem {
	for i := range a.Coverage {
		if strings.HasPrefix(a.Coverage[i].Scope, prefix) {
			return &a.Coverage[i]
		}
	}
	return nil
}

func TestParseRollerVersion(t *testing.T) {
	for in, want := range map[string]string{
		string(rollerProps("6.1.4")):                    "6.1.4",
		"ro.version=4.0.1\nro.revision=729109\n":        "4.0.1",
		"ro.version = 5.2.4\n":                          "5.2.4",
		"ro.version:6.1.6-SNAPSHOT\n":                   "6.1.6-SNAPSHOT",
		"ro.version=6.1.3\nro.version=6.1.4\n":          "6.1.4",
		"# ro.version=1.0\nro.version=6.1.4\n":          "6.1.4",
		"ro.version=6.1.4\n! ro.version=1.0\n":          "6.1.4",
		"ro.version=${project.version}\n":               "",
		"ro.version=UNKNOWN\n":                          "",
		"ro.version=6\n":                                "",
		"ro.version=6.1.4; rm -rf /\n":                  "",
		"ro.versions=6.1.4\n":                           "",
		"xro.version=6.1.4\n":                           "",
		"ro.version=" + strings.Repeat("6.", 500) + "1": "",
		"": "",
	} {
		got, ok := parseRollerVersion([]byte(in))
		if got != want || ok != (want != "") {
			t.Errorf("%q = %q %v, want %q", in, got, ok, want)
		}
	}
}

// Java web applications deployed in Tomcat are discovered: exploded
// directories with WEB-INF (in a container's webapps directory outside the
// bases, and under /opt), and a .war file the container has not unpacked;
// a WAR beside its unpacked directory, and a directory without WEB-INF,
// are not applications of their own.
func TestDiscoverJavaWebapps(t *testing.T) {
	tr := newTree(t)
	tr.file("var/lib/tomcat10/webapps/roller/WEB-INF/web.xml", "<web-app/>")
	tr.file("var/lib/tomcat10/webapps/ROOT/index.html", "<html>Tomcat</html>")
	tr.file("var/lib/tomcat10/webapps/shop/WEB-INF/web.xml", "<web-app/>")
	tr.file("var/lib/tomcat10/webapps/shop.war", string(zipOf(t, map[string][]byte{"WEB-INF/web.xml": nil})))
	tr.file("var/lib/tomcat10/webapps/blog.war", string(zipOf(t, map[string][]byte{"WEB-INF/web.xml": nil})))
	tr.file("var/lib/tomcat10/webapps/.hidden.war", "x")
	tr.file("opt/tomcat/webapps/api/WEB-INF/classes/x.class", "x")
	tr.file("opt/tomcat/webapps/legacy.war", string(zipOf(t, map[string][]byte{"WEB-INF/web.xml": nil})))
	tr.file("srv/portal/WEB-INF/web.xml", "<web-app/>")
	// A link is not a web application, nor read as a webapps directory.
	tr.file("elsewhere/outside/WEB-INF/web.xml", "<web-app/>")
	tr.link("var/lib/tomcat10/webapps/linked", tr.root+"/elsewhere/outside")
	tr.link("var/lib/tomcat10/webapps/linked.war", tr.root+"/var/lib/tomcat10/webapps/blog.war")
	tr.link("usr/local/tomcat/webapps", tr.root+"/elsewhere")

	found, full := (&Scanner{Root: tr.root}).DiscoverSites()
	got := map[string]string{}
	for _, d := range found {
		got[d.Dir] = strings.Join(d.By, ",")
	}
	want := map[string]string{
		"/var/lib/tomcat10/webapps/roller":   "WEB-INF",
		"/var/lib/tomcat10/webapps/shop":     "WEB-INF",
		"/var/lib/tomcat10/webapps/blog.war": "war",
		"/opt/tomcat/webapps/api":            "WEB-INF",
		"/opt/tomcat/webapps/legacy.war":     "war",
		"/srv/portal":                        "WEB-INF/web.xml",
	}
	if !full || len(got) != len(want) {
		t.Fatalf("found %v (full %v), want %v", got, full, want)
	}
	for d, by := range want {
		if got[d] != by {
			t.Errorf("%s: found by %q, want %q", d, got[d], by)
		}
	}
}

// Apache Roller is identified by the release in its roller-version.properties
// wherever a release puts it: WEB-INF/classes (5.2 and later), the root of
// one of its JARs in WEB-INF/lib (4.0's roller-business.jar, 5.0's
// roller-weblogger-business-5.0.4.jar), exploded or in a .war file. Without
// the Java stack pack the bundled JARs are a coverage gap.
func TestRollerRelease(t *testing.T) {
	tr := newTree(t)
	xmlrpc := mavenJar(t, "org.apache.xmlrpc", "xmlrpc-server", "3.1.3")
	tr.file("var/lib/tomcat10/webapps/roller/WEB-INF/web.xml", "<web-app/>")
	tr.file("var/lib/tomcat10/webapps/roller/WEB-INF/classes/roller-version.properties", string(rollerProps("6.1.4")))
	tr.file("var/lib/tomcat10/webapps/roller/WEB-INF/lib/xmlrpc-server-3.1.3.jar", string(xmlrpc))
	tr.file("opt/tomcat/webapps/blog/WEB-INF/web.xml", "<web-app/>")
	tr.file("opt/tomcat/webapps/blog/WEB-INF/lib/roller-business.jar", string(zipOf(t, map[string][]byte{
		"roller-version.properties": []byte("ro.version=4.0.1\nro.revision=729109\n"), "org/apache/roller/X.class": nil})))
	tr.file("opt/tomcat/webapps/old.war", string(zipOf(t, map[string][]byte{
		"WEB-INF/web.xml": nil,
		"WEB-INF/lib/roller-weblogger-business-5.0.4.jar": zipOf(t, map[string][]byte{"roller-version.properties": []byte("ro.version=5.0.4\n"),
			"META-INF/maven/org.apache.roller/roller-weblogger-business/pom.properties": pomProps("org.apache.roller", "roller-weblogger-business", "5.0.4")}),
		"WEB-INF/lib/xmlrpc-server-3.1.3.jar": xmlrpc,
	})))
	tr.file("var/lib/tomcat10/webapps/other/WEB-INF/web.xml", "<web-app/>")
	tr.file("var/lib/tomcat10/webapps/other/WEB-INF/classes/app.properties", "ro.version=9.9.9\n")

	s := &Scanner{Root: tr.root}
	for dir, c := range map[string]struct{ version, loc, inner string }{
		"/var/lib/tomcat10/webapps/roller": {"6.1.4", "/var/lib/tomcat10/webapps/roller/WEB-INF/classes/roller-version.properties", ""},
		"/opt/tomcat/webapps/blog":         {"4.0.1", "/opt/tomcat/webapps/blog/WEB-INF/lib/roller-business.jar", "roller-version.properties"},
		"/opt/tomcat/webapps/old.war":      {"5.0.4", "/opt/tomcat/webapps/old.war", "WEB-INF/lib/roller-weblogger-business-5.0.4.jar/roller-version.properties"},
	} {
		a := s.ScanApp(context.Background(), dir)
		validate(t, a)
		o := findPurl(a, "pkg:generic/apache-roller@")
		if o == nil {
			t.Fatalf("%s: no Roller: %+v %+v", dir, a.Observations, a.Coverage)
		}
		if o.Purl != "pkg:generic/apache-roller@"+c.version || o.Version != c.version || o.Location != c.loc || o.Confidence != model.ConfidenceConfirmed ||
			o.Evidence["kind"] != KindJavaWebapp || o.Evidence["product"] != "Apache Roller" || o.Evidence["archive_path"] != c.inner || o.Evidence["app_dir"] != dir {
			t.Errorf("%s: %+v", dir, *o)
		}
		if findPurl(a, "pkg:maven/") != nil {
			t.Errorf("%s: Maven packages without a pack: %+v", dir, a.Observations)
		}
		gap := findScope(a, JavaLibrariesScope)
		if gap == nil || gap.Status != "unsupported" || !strings.Contains(gap.Reason, "Java stack pack") || !a.UnreadJavaLibraries() {
			t.Errorf("%s: JAR gap: %+v", dir, a.Coverage)
		}
	}
	if a := s.ScanApp(context.Background(), "/opt/tomcat/webapps/old.war"); a.Name != "old" || a.Dir != "/opt/tomcat/webapps/old.war" ||
		findScope(a, WarScope+"/opt/tomcat/webapps/old.war").Status != "checked" {
		t.Errorf("war app: %s %s %+v", a.Name, a.Dir, a.Coverage)
	}
	// Another web application's properties file is not Roller's.
	if a := s.ScanApp(context.Background(), "/var/lib/tomcat10/webapps/other"); len(a.Observations) != 0 || a.UnreadJavaLibraries() {
		t.Errorf("other: %+v %+v", a.Observations, a.Coverage)
	}
}

// With the Java stack pack, the libraries in WEB-INF/lib are reported as
// Maven packages, exploded or in a .war file, and the pack is given only the
// WAR being scanned, not the other applications beside it.
func TestJavaWebappLibrariesThroughPack(t *testing.T) {
	tr := newTree(t)
	axis := mavenJar(t, "axis", "axis", "1.4")
	tr.file("var/lib/tomcat10/webapps/svc/WEB-INF/web.xml", "<web-app/>")
	tr.file("var/lib/tomcat10/webapps/svc/WEB-INF/lib/axis-1.4.jar", string(axis))
	tr.file("var/lib/tomcat10/webapps/old.war", string(zipOf(t, map[string][]byte{"WEB-INF/lib/axis-1.4.jar": axis,
		"WEB-INF/classes/roller-version.properties": rollerProps("6.1.4")})))
	tr.file("var/lib/tomcat10/webapps/other.war", string(zipOf(t, map[string][]byte{"WEB-INF/lib/other-1.0.jar": mavenJar(t, "com.acme", "other", "1.0")})))
	var given []string
	s := &Scanner{Root: tr.root}
	s.Packs = append(s.Packs, javaPack{files: &given})

	a := s.ScanApp(context.Background(), "/var/lib/tomcat10/webapps/svc")
	validate(t, a)
	if o := findPurl(a, "pkg:maven/axis/axis@1.4"); o == nil || o.Location != "/var/lib/tomcat10/webapps/svc/WEB-INF/lib/axis-1.4.jar" {
		t.Errorf("exploded: %+v", a.Observations)
	}
	if a.UnreadJavaLibraries() {
		t.Errorf("exploded: gap with the pack: %+v", a.Coverage)
	}

	given = nil
	a = s.ScanApp(context.Background(), "/var/lib/tomcat10/webapps/old.war")
	validate(t, a)
	if o := findPurl(a, "pkg:maven/axis/axis@1.4"); o == nil || o.Location != "/var/lib/tomcat10/webapps/old.war" || o.Evidence["source"] != "archive" {
		t.Errorf("war: %+v", a.Observations)
	}
	if findPurl(a, "pkg:generic/apache-roller@6.1.4") == nil || findPurl(a, "pkg:maven/com.acme/other") != nil || a.UnreadJavaLibraries() {
		t.Errorf("war: %+v %+v", a.Observations, a.Coverage)
	}
	if !slices.Equal(given, []string{"old.war"}) {
		t.Errorf("the pack was given %v", given)
	}
	if c := findScope(a, "pack:java:"); c == nil || c.Scope != "pack:java:/var/lib/tomcat10/webapps/old.war" {
		t.Errorf("pack coverage: %+v", a.Coverage)
	}
}

// Hostile and broken deployments: links out of the application are not
// followed, archive bombs and oversized entries are refused without
// reading them, too many entries stop the read, and a broken WAR is a
// failed coverage item. Every batch stays valid.
func TestHostileJavaWebapps(t *testing.T) {
	tr := newTree(t)
	tr.file("secret/roller-version.properties", string(rollerProps("6.1.4")))
	tr.file("secret/lib/roller-business.jar", string(zipOf(t, map[string][]byte{"roller-version.properties": rollerProps("6.1.4")})))
	w := "var/lib/tomcat10/webapps/"
	// WEB-INF/classes, WEB-INF/lib and the properties file itself linking out.
	tr.file(w+"a/WEB-INF/web.xml", "<web-app/>")
	tr.link(w+"a/WEB-INF/classes", tr.root+"/secret")
	tr.link(w+"a/WEB-INF/lib", tr.root+"/secret/lib")
	tr.file(w+"b/WEB-INF/web.xml", "<web-app/>")
	tr.link(w+"b/WEB-INF/classes/roller-version.properties", tr.root+"/secret/roller-version.properties")
	tr.link(w+"b/WEB-INF/lib/roller-business.jar", tr.root+"/secret/lib/roller-business.jar")
	// A properties file far larger than any Roller writes, a JAR that
	// is not a zip, and a hostile version.
	tr.file(w+"c/WEB-INF/classes/roller-version.properties", "ro.version=6.1.4"+strings.Repeat(" ", 200<<10)+"\n")
	tr.file(w+"c/WEB-INF/lib/roller-core.jar", "not a zip")
	tr.file(w+"d/WEB-INF/classes/roller-version.properties", "ro.version=6.1.4\x00<script>\n")
	// A WAR whose properties file and nested Roller JAR decompress to far
	// more than the limits (a few KB compressed).
	bomb := bytes.Repeat([]byte{'0'}, maxNestedJar+1)
	tr.file(w+"bomb.war", string(zipOf(t, map[string][]byte{
		"WEB-INF/classes/roller-version.properties": append([]byte("ro.version=6.1.4\n#"), bytes.Repeat([]byte{'x'}, maxPropertiesSize)...),
		"WEB-INF/lib/roller-business.jar":           bomb,
	})))
	tr.file(w+"broken.war", "PK\x03\x04 not really")
	// Nested deeper than WAR > JAR: a WAR in a Roller JAR is not opened.
	inner := zipOf(t, map[string][]byte{"WEB-INF/classes/roller-version.properties": rollerProps("6.1.4")})
	tr.file(w+"deep.war", string(zipOf(t, map[string][]byte{"WEB-INF/lib/roller-x.jar": zipOf(t, map[string][]byte{"inner.war": inner})})))

	s := &Scanner{Root: tr.root}
	for _, dir := range []string{"a", "b", "c", "d", "bomb.war", "broken.war", "deep.war"} {
		start := time.Now()
		a := s.ScanApp(context.Background(), "/"+w+dir)
		validate(t, a)
		if o := findPurl(a, "pkg:generic/apache-roller"); o != nil {
			t.Errorf("%s: read Roller where it must not: %+v", dir, *o)
		}
		if d := time.Since(start); d > 5*time.Second {
			t.Errorf("%s: took %s", dir, d)
		}
		if dir == "broken.war" {
			if c := findScope(a, WarScope); c == nil || c.Status != "failed" {
				t.Errorf("broken: %+v", a.Coverage)
			}
		}
	}

	// Too many entries: the archive is not read.
	defer func(n int) { maxArchiveEntries = n }(maxArchiveEntries)
	maxArchiveEntries = 3
	tr.file(w+"many.war", string(zipOf(t, map[string][]byte{"WEB-INF/classes/roller-version.properties": rollerProps("6.1.4"),
		"a": nil, "b": nil, "c": nil})))
	a := s.ScanApp(context.Background(), "/"+w+"many.war")
	validate(t, a)
	if c := findScope(a, WarScope); findPurl(a, "pkg:generic/") != nil || c == nil || c.Status != "failed" || !strings.Contains(c.Reason, "entries") {
		t.Errorf("many: %+v %+v", a.Observations, a.Coverage)
	}
	// A link named .war is not scanned as a WAR.
	tr.link(w+"linked.war", tr.root+"/"+w+"deep.war")
	if a := s.ScanApp(context.Background(), "/"+w+"linked.war"); findScope(a, WarScope) != nil || len(a.Observations) != 0 {
		t.Errorf("linked war: %+v", a)
	}
}

// An unreadable WAR is reported as such, as an unreadable directory is.
func TestUnreadableWar(t *testing.T) {
	tr := newTree(t)
	tr.file("var/lib/tomcat10/webapps/x.war", string(zipOf(t, map[string][]byte{"WEB-INF/web.xml": nil})))
	tr.unreadable("var/lib/tomcat10/webapps/x.war")
	a := (&Scanner{Root: tr.root}).ScanApp(context.Background(), "/var/lib/tomcat10/webapps/x.war")
	if !a.Unreadable || findScope(a, PermissionScope) == nil {
		t.Errorf("%+v", a)
	}
}
